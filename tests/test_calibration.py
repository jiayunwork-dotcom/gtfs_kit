def test_calibrated_stop_times_uses_prepared_shape_mileage():
    # Step 2 consumes step 1's ruler; it does not silently regenerate one.
    unprepared = foldback()
    unprepared.shapes = unprepared.shapes.drop(columns=["shape_dist_traveled"])
