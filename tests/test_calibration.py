def test_calibrated_locate_mid_segment_coordinates():
    feed = calibrated_foldback()
    # 08:10 is the outbound C; 08:30 is the inbound C.
    result = gk.locate_trips(feed, DATE, ["08:10:00", "08:30:00"], calibrated=True)
    result = result.set_index("time")

    lon_out, lat_out = expected_lonlat(400, 0)
    lon_in, lat_in = expected_lonlat(400, 10)
    assert result.loc["08:10:00", "lon"] == pytest.approx(lon_out, abs=1e-6)
    assert result.loc["08:10:00", "lat"] == pytest.approx(lat_out, abs=1e-6)
    assert result.loc["08:30:00", "lon"] == pytest.approx(lon_in, abs=1e-6)
    assert result.loc["08:30:00", "lat"] == pytest.approx(lat_in, abs=1e-6)

    # rel_dist spans the first and last timed stops.
    assert result.loc["08:10:00", "rel_dist"] == pytest.approx(500 / 1500)
    assert result.loc["08:30:00", "rel_dist"] == pytest.approx(1300 / 1500)


