def test_calibrated_shapes_keeps_complete_ticks_verbatim():
    feed = foldback()
    result = feed.append_dist_to_shapes(calibrated=True)
    shapes = result.shapes.sort_values(["shape_id", "shape_pt_sequence"])
    assert shapes["shape_dist_traveled"].tolist() == pytest.approx(TICKS)
    # The first tick need not be zero, and is preserved.
    assert shapes["shape_dist_traveled"].iloc[0] == 100
    # The caller's feed is untouched: same object contents as before.
    assert feed.shapes["shape_dist_traveled"].tolist() == TICKS


def test_calibrated_shapes_generates_missing_mileage_in_feed_units():
    feed = foldback()
    feed.shapes = feed.shapes.drop(columns=["shape_dist_traveled"])
    result = feed.append_dist_to_shapes(calibrated=True)
    ticks = result.shapes.sort_values("shape_pt_sequence")["shape_dist_traveled"]
    # Starts at zero, strictly increasing, and ends near the true length:
    # 800 m out + 10 m jog + 800 m back.
    assert ticks.iloc[0] == 0
    assert (np.diff(ticks.values) > 0).all()
    assert ticks.iloc[-1] == pytest.approx(1610, abs=2)

    # In kilometres the generated tick column is the same length scaled down.
    km_feed = foldback("km")
    km_feed.shapes = km_feed.shapes.drop(columns=["shape_dist_traveled"])
    km_result = km_feed.append_dist_to_shapes(calibrated=True)
    km_ticks = km_result.shapes.sort_values("shape_pt_sequence")["shape_dist_traveled"]
    assert km_ticks.iloc[-1] == pytest.approx(1.610, abs=0.002)


def test_calibrated_shapes_rejects_bad_vertex_tables():
    feed = foldback()

    # Partially filled mileage.
    bad = feed.copy()
    bad.shapes.loc[bad.shapes.index[:2], "shape_dist_traveled"] = np.nan
    with pytest.raises(ValueError, match="fold_shape"):
        bad.append_dist_to_shapes(calibrated=True)

    # Non-strictly-increasing mileage.
    flat = feed.copy()
    flat.shapes.loc[flat.shapes.index[1], "shape_dist_traveled"] = 100
    with pytest.raises(ValueError, match="fold_shape"):
        flat.append_dist_to_shapes(calibrated=True)

    # Negative mileage.
    negative = feed.copy()
    negative.shapes.loc[negative.shapes.index[0], "shape_dist_traveled"] = -1
    with pytest.raises(ValueError, match="fold_shape"):
        negative.append_dist_to_shapes(calibrated=True)

    # Duplicate vertex sequence.
    duplicate = feed.copy()
    duplicate.shapes.loc[duplicate.shapes.index[1], "shape_pt_sequence"] = 10
    with pytest.raises(ValueError, match="fold_shape"):
        duplicate.append_dist_to_shapes(calibrated=True)

    # Coincident adjacent vertices.
    coincident = feed.copy()
    coincident.shapes.loc[coincident.shapes.index[1], "shape_pt_lon"] = (
        coincident.shapes.loc[coincident.shapes.index[0], "shape_pt_lon"]
    )
    coincident.shapes.loc[coincident.shapes.index[1], "shape_pt_lat"] = (
        coincident.shapes.loc[coincident.shapes.index[0], "shape_pt_lat"]
    )
    with pytest.raises(ValueError, match="fold_shape"):
        coincident.append_dist_to_shapes(calibrated=True)


