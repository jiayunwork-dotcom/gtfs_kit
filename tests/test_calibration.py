def test_calibrated_stop_times_is_row_order_independent():
    feed = foldback()
    result1 = feed.append_dist_to_shapes(calibrated=True).append_dist_to_stop_times(
        calibrated=True, max_offset_m=20
    )

    shuffled = foldback()
    shuffled.stop_times = shuffled.stop_times.sample(frac=1, random_state=7).reset_index(
        drop=True
    )
    result2 = shuffled.append_dist_to_shapes(calibrated=True).append_dist_to_stop_times(
        calibrated=True, max_offset_m=20
    )

    key = ["trip_id", "stop_sequence"]
    a = result1.stop_times.sort_values(key).reset_index(drop=True)
    b = result2.stop_times.sort_values(key).reset_index(drop=True)
    pd.testing.assert_frame_equal(a, b)


def test_calibrated_stop_times_does_not_leak_between_trips():
    """Two trips on the same shape are matched independently."""
    feed = foldback()
    # Add a second full run whose stops should be matched on their own terms.
    extra = feed.trips.iloc[[0]].copy()
    extra["trip_id"] = "full_trip_2"
    feed.trips = pd.concat([feed.trips, extra], ignore_index=True)
    extra_st = feed.stop_times.loc[feed.stop_times.trip_id == "full_trip"].copy()
    extra_st["trip_id"] = "full_trip_2"
    feed.stop_times = pd.concat([feed.stop_times, extra_st], ignore_index=True)

    result = feed.append_dist_to_shapes(calibrated=True).append_dist_to_stop_times(
        calibrated=True, max_offset_m=20
    )
    st = result.stop_times.sort_values(["trip_id", "stop_sequence"])
    g1 = st.loc[st.trip_id == "full_trip", "shape_dist_traveled"].values
    g2 = st.loc[st.trip_id == "full_trip_2", "shape_dist_traveled"].values
    assert np.allclose(g1, g2)


