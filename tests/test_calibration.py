def test_calibrated_stop_times_separates_the_two_passes():
    result = calibrated_foldback()
    st = result.stop_times
    full = st.loc[st.trip_id == "full_trip"].sort_values("stop_sequence")

    # The outbound visit to C comes before the intermediate stops and the
    # inbound visit comes after them, with different mileage.
    outbound_c = full.loc[full.stop_sequence == 3, "shape_dist_traveled"].iat[0]
    inbound_c = full.loc[full.stop_sequence == 7, "shape_dist_traveled"].iat[0]
    assert outbound_c == pytest.approx(600)
    assert inbound_c == pytest.approx(1400, abs=0.01)
    assert inbound_c > outbound_c

    # Mileage is non-decreasing over the whole trip.
    assert (np.diff(full["shape_dist_traveled"].values) >= -1e-9).all()
    # Every stop got a value.
    assert st["shape_dist_traveled"].notna().all()


def test_calibrated_stop_times_short_working_uses_its_own_span():
    result = calibrated_foldback()
    st = result.stop_times
    short = st.loc[st.trip_id == "short_trip"].sort_values("stop_sequence")

    # B, C, D on the outbound leg, not the full-shape mileage.
    assert short["shape_dist_traveled"].tolist() == pytest.approx([350, 600, 850])


def test_calibrated_stop_times_anchors_are_kept():
    feed = foldback()
    # Anchor the outbound C at its outbound mileage.
    feed.stop_times["shape_dist_traveled"] = np.nan
    mask = (feed.stop_times.trip_id == "full_trip") & (feed.stop_times.stop_sequence == 3)
    feed.stop_times.loc[mask, "shape_dist_traveled"] = 600.0

    result = feed.append_dist_to_shapes(calibrated=True).append_dist_to_stop_times(
        calibrated=True, max_offset_m=20
    )
    full = result.stop_times.loc[result.stop_times.trip_id == "full_trip"].sort_values(
        "stop_sequence"
    )
    assert full.loc[full.stop_sequence == 3, "shape_dist_traveled"].iat[0] == 600.0


def test_calibrated_stop_times_rejects_out_of_radius_anchor():
    feed = foldback()
    feed.stop_times["shape_dist_traveled"] = np.nan
    # Point the anchor at the inbound pass (y = +10 m) with a tiny radius, so
    # the anchor's mileage no longer lies within reach of the outbound stop.
