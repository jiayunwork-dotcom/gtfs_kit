def test_calibrated_locate_handles_times_after_midnight():
    feed = calibrated_foldback()
    # Shift the full trip's times to 24:00-24:40, still that service day.
    shifted = feed.copy()
    mask = shifted.stop_times.trip_id == "full_trip"
    times = shifted.stop_times.loc[mask, "departure_time"].map(
        lambda t: gk.helpers.seconds_to_timestr(
            gk.helpers.timestr_to_seconds(t) + 16 * 3600
        )
    )
    shifted.stop_times.loc[mask, "departure_time"] = times
    shifted.stop_times.loc[mask, "arrival_time"] = times
    result = gk.locate_trips(shifted, DATE, ["24:10:00", "24:30:00"], calibrated=True)
    assert not result.empty
    assert set(result.trip_id) == {"full_trip"}
    assert set(result.time) == {"24:10:00", "24:30:00"}


