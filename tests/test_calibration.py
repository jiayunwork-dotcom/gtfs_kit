def test_segment_index_matches_linear_scan():
    """On long shapes the STRtree candidate search must find every interval."""
    # A 200-vertex zig-zag with many self-crossings, so > 32 segments and the
    # spatial index path is exercised.
    n = 200
    lon = np.array([145.77 + (i % 10) * 100.0 / (111320 * 0.957) for i in range(n)])
    lat = np.array(
        [-16.92 + (0.0 if (i // 10) % 2 == 0 else 50.0) / 111320 for i in range(n)]
    )
    dist = np.arange(n, dtype=float) * 10
    record = {
        "s": {
            "shape_id": "s",
            "sequence": np.arange(n),
            "lon": lon,
            "lat": lat,
            "dist": dist,
        }
    }
    geom = cb.build_shape_geometries(record)["s"]
    assert geom.n_segments > 32

    from gtfs_kit.calibration import project_to_utm

    sx, sy, _ = project_to_utm(np.array([145.771]), np.array([-16.91999]))
    sx, sy = float(sx[0]), float(sy[0])
    for radius in [5.0, 20.0, 200.0]:
        indexed = geom.intervals_for_stop("q", sx, sy, radius)
        linear = []
        for j in range(geom.n_segments):
            iv = geom._segment_interval(j, sx, sy, radius)
            if iv is not None:
                linear.append(iv)
        linear = cb._merge_intervals(sorted(linear, key=lambda z: (z[0], z[1])))
        assert len(indexed) == len(linear)
        for a, b in zip(indexed, linear):
            assert a[0] == pytest.approx(b[0], abs=1e-9)
            assert a[1] == pytest.approx(b[1], abs=1e-9)


def test_calibrated_stop_times_handles_a_late_partial_working():
    # A trip that only serves the tail: D, C, B, A.  Every value must be
    # non-decreasing, on the shape, and within the matching radius of its
    # stop; revisits let the chain switch passes where that stays consistent.
    feed = foldback()
    feed.stop_times["shape_dist_traveled"] = np.nan
    rest = feed.stop_times.loc[feed.stop_times.trip_id != "short_trip"]
    tail = pd.DataFrame(
        {
            "trip_id": ["short_trip"] * 4,
            "arrival_time": ["10:00:00", "10:05:00", "10:10:00", "10:15:00"],
            "departure_time": ["10:00:00", "10:05:00", "10:10:00", "10:15:00"],
            "stop_id": ["D", "C", "B", "A"],
            "stop_sequence": [1, 2, 3, 4],
        }
    )
    feed.stop_times = pd.concat([rest, tail], ignore_index=True)

    result = feed.append_dist_to_shapes(calibrated=True).append_dist_to_stop_times(
        calibrated=True, max_offset_m=20
    )
    got = (
        result.stop_times.loc[result.stop_times.trip_id == "short_trip"]
        .sort_values("stop_sequence")["shape_dist_traveled"]
        .to_numpy()
    )
    assert (np.diff(got) >= -1e-9).all()
    assert got[0] >= 850 - 1e-6  # starts no earlier than outbound D
    assert got[-1] <= 1600 + 1e-6  # ends no later than the shape's last tick

    # Each chosen distance is genuinely on the shape within the radius.
    record = cb.prepare_shape_distances(result.shapes, "m", generate_missing=False)[
        "fold_shape"
    ]
    geom = cb.build_shape_geometries({"fold_shape": record})["fold_shape"]
    from gtfs_kit.calibration import project_to_utm

    st = result.stops
    x, y, _ = project_to_utm(st.stop_lon.values, st.stop_lat.values)
    xy = dict(zip(st.stop_id, zip(x, y)))
    tail_st = result.stop_times.loc[
        result.stop_times.trip_id == "short_trip"
    ].sort_values("stop_sequence")
    for _, row in tail_st.iterrows():
        _, _, px, py, _, _ = geom.locate_distance(row["shape_dist_traveled"])
        sx, sy = xy[row["stop_id"]]
        assert np.hypot(sx - px, sy - py) <= 20 + 1e-6


