"""
Tests for the optional calibrated mileage workflows:

- ``Feed.append_dist_to_shapes(calibrated=True)``
- ``Feed.append_dist_to_stop_times(calibrated=True, max_offset_m=...)``
- ``Feed.locate_trips(..., calibrated=True)``

The fold-back fixture in ``tests/fixtures/foldback_gtfs.zip`` is generated by
``scripts/make_foldback_fixture.py``.  It has a shape that runs A -> E and
back, a stop that is served twice, and a short working that covers only the
middle of the shape.  Its shape mileage ticks are deliberately non-uniform.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from .context import DATA_DIR, cairns
import gtfs_kit as gk
from gtfs_kit import calibration as cb

FIXTURE = DATA_DIR.parent / "tests" / "fixtures" / "foldback_gtfs.zip"
DATE = "20250106"

# Outbound/inbound geometry constants, mirrored from the fixture generator.
LON0, LAT0 = 145.7700, -16.9200
DEG_PER_M_LAT = 1 / 111_320.0
DEG_PER_M_LON = 1 / (111_320.0 * 0.957)

TICKS = [100, 350, 600, 850, 1100, 1200, 1300, 1400, 1500, 1600]


def foldback(dist_units="m"):
    return gk.read_feed(FIXTURE, dist_units=dist_units)


def calibrated_foldback(dist_units="m", max_offset_m=20):
    feed = foldback(dist_units)
    return feed.append_dist_to_shapes(calibrated=True).append_dist_to_stop_times(
        calibrated=True, max_offset_m=max_offset_m
    )


def expected_lonlat(x_m, y_m):
    return LON0 + x_m * DEG_PER_M_LON, LAT0 + y_m * DEG_PER_M_LAT


